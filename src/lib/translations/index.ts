export function t(key: string, lang: string = DEFAULT_LANGUAGE): string {
  return translations[lang]?.[key] ?? translations[DEFAULT_LANGUAGE]?.[key] ?? key
}

export function getTranslations(lang: string = DEFAULT_LANGUAGE): Record<string, string> {
  return translations[lang] ?? translations[DEFAULT_LANGUAGE]
}

export function getLanguageInfo(lang: string): { code: string; name: string; dir: 'ltr' | 'rtl'; locale: string } | null {
  const info = LANGUAGES.find(l => l.code === lang)
  if (info) return info
  return { code: DEFAULT_LANGUAGE, name: 'English', dir: 'ltr', locale: 'en-US' }
}
